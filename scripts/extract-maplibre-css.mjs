/**
 * The explorer uses a twentieth of maplibre-gl.css: the canvas
 * plumbing and the compact attribution control. The rest (popups,
 * markers, zoom and compass controls with their embedded icons) is
 * 80 KB the visitor pays for on every prefetch of /explore. This
 * script distills the rules we actually use into
 * app/explore/maplibre-core.css.
 *
 * Usage: node scripts/extract-maplibre-css.mjs   (run after upgrading maplibre-gl)
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const KEEP =
  /\.maplibregl-(map(?![a-z-])|canvas|ctrl(?![a-z-])|ctrl-bottom|ctrl-top|ctrl-attrib|attrib|touch|interactive|pseudo-fullscreen)/;

// buttons this app never renders, with their embedded icons
const DROP =
  /\.maplibregl-ctrl-(zoom|compass|geolocate|fullscreen|shrink|globe|terrain|scale|logo)|\.maplibregl-ctrl-icon/;

/** minified css → [{prelude, body}] with @-blocks kept whole */
function splitRules(css) {
  const rules = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) break;
    const prelude = css.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    rules.push({ prelude, body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return rules;
}

function filterCss(css) {
  const out = [];
  for (const { prelude, body } of splitRules(css)) {
    if (prelude.startsWith("@")) {
      // conditional group (@media and friends): keep what survives inside
      const inner = filterCss(body);
      if (inner) out.push(`${prelude}{${inner}}`);
    } else if (KEEP.test(prelude) && !DROP.test(prelude)) {
      out.push(`${prelude}{${body}}`);
    }
  }
  return out.join("\n");
}

const src = path.join(process.cwd(), "node_modules", "maplibre-gl", "dist", "maplibre-gl.css");
const dst = path.join(process.cwd(), "app", "explore", "maplibre-core.css");
const css = await readFile(src, "utf8");
const kept = filterCss(css);
const header =
  "/* Generated by scripts/extract-maplibre-css.mjs — the slice of\n" +
  "   maplibre-gl.css this app actually uses. Do not edit by hand;\n" +
  "   rerun the script after upgrading maplibre-gl. */\n";
await writeFile(dst, header + kept + "\n");
console.log(`maplibre-gl.css ${css.length} bytes → maplibre-core.css ${kept.length} bytes`);
